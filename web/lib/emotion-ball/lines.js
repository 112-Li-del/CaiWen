/**
 * 从台词库里抽一句，避开上一句（连着说同一句很出戏）。
 * rnd 可注入，测试里换成固定种子就完全可复现。
 * @param {string[]} pool
 * @param {string} avoid 上一句
 * @param {() => number} [rnd]
 */
export function pickLine(pool, avoid, rnd = Math.random) {
  if (!pool || !pool.length) return '';
  let line = pool[Math.floor(rnd() * pool.length) % pool.length];
  if (pool.length > 1 && line === avoid) {
    line = pool[(pool.indexOf(line) + 1) % pool.length];
  }
  return line;
}
