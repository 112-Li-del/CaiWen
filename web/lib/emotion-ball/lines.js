/* ============================================================
 * lines.js —— 待机台词库
 * ------------------------------------------------------------
 * 待机时总说一句「我在呢，随便问～」太闷，所以攒了一批句子按动作轮次轮换。
 * 轮换规则不在本文件，在 states.js 的 tipLines / tipRounds + engine 的
 * rotateTip()：前 N 轮说表情自己的 tip，之后每轮随机换一句。
 *
 * 三条写作约束（改动本文件时请遵守）：
 *   1. **短**：上限 12 个字符。球的台词容器宽度是 size+40（size 96 → 136px），
 *      12px 字号下超过 12 字就要折行，而球是贴着输入框底边定位的，折行会往
 *      下顶出容器。
 *   2. **不署名**：名人名言只取耳熟能详的短句原文，不标作者——标错作者比不标
 *      更糟（网上流传的「爱因斯坦说复利」之类大多查无出处）。
 *   3. **不给具体投资建议**：财经类只讲概念（现金流量、机会成本），不提任何
 *      具体标的、收益率或"该不该买"。
 *
 * 分类只是便于维护，运行时是打散后统一随机抽的。
 * ============================================================ */

